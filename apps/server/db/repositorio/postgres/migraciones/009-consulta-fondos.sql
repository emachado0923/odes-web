-- =============================================================================
-- Migración 9 (Postgres): ventanilla de consulta de los fondos. La misma de
-- db/repositorio/migraciones/009-consulta-fondos.sql (MySQL), traducida: ver
-- allí qué guarda cada tabla. Las fichas tienen datos personales: RLS activo y
-- sin permisos para anon/authenticated (solo las lee el servidor).
-- =============================================================================

CREATE TABLE IF NOT EXISTS sivu_tablero_fondos_2026_fichas (
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  documento     varchar(40) NOT NULL,
  programa      varchar(16) NOT NULL,
  convocatoria  varchar(60) NOT NULL,
  ficha         text        NOT NULL,
  CONSTRAINT fondos_2026_fichas_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_fondos_2026_fichas_documento ON sivu_tablero_fondos_2026_fichas (documento);

CREATE TABLE IF NOT EXISTS sivu_tablero_fondos_2026_consultas (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  usuario     varchar(64) COLLATE repositorio_ci NOT NULL,
  documento   varchar(40) NOT NULL,
  resultados  integer     NOT NULL,
  ip          varchar(45) NULL,
  creado_en   timestamptz(3) NOT NULL,
  CONSTRAINT fondos_2026_consultas_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_fondos_2026_consultas_usuario ON sivu_tablero_fondos_2026_consultas (usuario, creado_en);
CREATE INDEX IF NOT EXISTS ix_fondos_2026_consultas_documento ON sivu_tablero_fondos_2026_consultas (documento);

ALTER TABLE sivu_tablero_fondos_2026_fichas ENABLE ROW LEVEL SECURITY;
ALTER TABLE sivu_tablero_fondos_2026_consultas ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
     AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON sivu_tablero_fondos_2026_fichas, sivu_tablero_fondos_2026_consultas FROM anon, authenticated;
  END IF;
END
$$;
