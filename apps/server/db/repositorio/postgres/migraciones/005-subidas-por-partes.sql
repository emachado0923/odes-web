-- Migración 5 (Postgres): subidas por partes. La misma de
-- db/repositorio/migraciones/005-subidas-por-partes.sql (MySQL), traducida.
-- Se aplica dentro de la transacción de `npm run repositorio:migrar`.
-- =============================================================================

CREATE TABLE IF NOT EXISTS repositorio_subidas (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  ruta        varchar(120) NOT NULL,
  usuario_id  integer      NOT NULL,
  bytes       bigint       NOT NULL,
  creado_en   timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT repositorio_subidas_pkey PRIMARY KEY (id),
  CONSTRAINT uq_repositorio_subidas_ruta UNIQUE (ruta),
  CONSTRAINT fk_repositorio_subidas_usuario FOREIGN KEY (usuario_id)
    REFERENCES repositorio_administradores (id) ON DELETE CASCADE,
  CONSTRAINT ck_repositorio_subidas_bytes CHECK (bytes > 0)
);
CREATE INDEX IF NOT EXISTS ix_repositorio_subidas_usuario ON repositorio_subidas (usuario_id, creado_en);
CREATE INDEX IF NOT EXISTS ix_repositorio_subidas_fecha ON repositorio_subidas (creado_en);

CREATE TABLE IF NOT EXISTS repositorio_subida_partes (
  subida_id  bigint  NOT NULL,
  n          integer NOT NULL,
  datos      bytea   NOT NULL,
  CONSTRAINT repositorio_subida_partes_pkey PRIMARY KEY (subida_id, n),
  CONSTRAINT fk_repositorio_subida_partes_subida FOREIGN KEY (subida_id)
    REFERENCES repositorio_subidas (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS pai_subida_partes (
  subida_id  integer NOT NULL,
  n          integer NOT NULL,
  datos      bytea   NOT NULL,
  CONSTRAINT pai_subida_partes_pkey PRIMARY KEY (subida_id, n),
  CONSTRAINT fk_pai_subida_partes_subida FOREIGN KEY (subida_id)
    REFERENCES pai_subidas (id) ON DELETE CASCADE
);

ALTER TABLE pai_subidas ADD COLUMN IF NOT EXISTS bytes bigint NULL;

-- Cerrado a la API pública de Supabase, como el resto del esquema.
ALTER TABLE repositorio_subidas ENABLE ROW LEVEL SECURITY;
ALTER TABLE repositorio_subida_partes ENABLE ROW LEVEL SECURITY;
ALTER TABLE pai_subida_partes ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
     AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON repositorio_subidas, repositorio_subida_partes, pai_subida_partes FROM anon, authenticated;
  END IF;
END
$$;
