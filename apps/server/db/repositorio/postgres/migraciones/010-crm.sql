CREATE TABLE IF NOT EXISTS crm_almacen_archivos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  sha256        char(64)     NOT NULL,
  mime          varchar(127) NOT NULL,
  bytes         bigint       NOT NULL,
  trozos        integer      NOT NULL,
  tamano_trozo  integer      NOT NULL,
  ancho         integer      NULL,
  alto          integer      NULL,
  creado_en     timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT crm_almacen_archivos_pkey PRIMARY KEY (id),
  CONSTRAINT uq_crm_almacen_archivos_sha256 UNIQUE (sha256),
  CONSTRAINT ck_crm_almacen_archivos_trozo CHECK (tamano_trozo > 0),
  CONSTRAINT ck_crm_almacen_archivos_bytes CHECK (bytes >= 0 AND trozos >= 0)
);

CREATE TABLE IF NOT EXISTS crm_almacen_archivo_trozos (
  archivo_id  bigint  NOT NULL,
  n           integer NOT NULL,
  datos       bytea   NOT NULL,
  CONSTRAINT crm_almacen_archivo_trozos_pkey PRIMARY KEY (archivo_id, n),
  CONSTRAINT fk_crm_almacen_archivo_trozos_archivo FOREIGN KEY (archivo_id)
    REFERENCES crm_almacen_archivos (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS crm_personas (
  id               integer GENERATED BY DEFAULT AS IDENTITY,
  nombre           varchar(120) NOT NULL,
  correo           varchar(254) COLLATE repositorio_ci NOT NULL,
  es_lider         smallint     NOT NULL DEFAULT 0,
  activo           smallint     NOT NULL DEFAULT 1,
  orden            integer      NOT NULL DEFAULT 0,
  foto_archivo_id  bigint       NULL,
  foto_version     integer      NOT NULL DEFAULT 0,
  creado_en        timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en   timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT crm_personas_pkey PRIMARY KEY (id),
  CONSTRAINT uq_crm_personas_correo UNIQUE (correo),
  CONSTRAINT fk_crm_personas_foto FOREIGN KEY (foto_archivo_id) REFERENCES crm_almacen_archivos (id),
  CONSTRAINT ck_crm_personas_lider CHECK (es_lider IN (0, 1)),
  CONSTRAINT ck_crm_personas_activo CHECK (activo IN (0, 1)),
  CONSTRAINT ck_crm_personas_foto_version CHECK (foto_version >= 0)
);
CREATE INDEX IF NOT EXISTS ix_crm_personas_orden ON crm_personas (activo, orden);
CREATE INDEX IF NOT EXISTS ix_crm_personas_foto ON crm_personas (foto_archivo_id);

CREATE TABLE IF NOT EXISTS crm_tareas (
  id                   integer GENERATED BY DEFAULT AS IDENTITY,
  titulo               varchar(160) NOT NULL,
  descripcion          text         NOT NULL,
  responsable_id       integer      NOT NULL,
  estado               varchar(12)  NOT NULL DEFAULT 'pendiente',
  fecha_limite         date         NULL,
  requiere_entregable  smallint     NOT NULL DEFAULT 0,
  nota_cierre          text         NULL,
  avisada_en           timestamptz(3) NULL,
  iniciada_en          timestamptz(3) NULL,
  terminada_en         timestamptz(3) NULL,
  eliminada_en         timestamptz(3) NULL,
  creado_en            timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en       timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT crm_tareas_pkey PRIMARY KEY (id),
  CONSTRAINT fk_crm_tareas_responsable FOREIGN KEY (responsable_id) REFERENCES crm_personas (id),
  CONSTRAINT ck_crm_tareas_estado CHECK (estado IN ('pendiente', 'en_proceso', 'terminada')),
  CONSTRAINT ck_crm_tareas_entregable CHECK (requiere_entregable IN (0, 1))
);
CREATE INDEX IF NOT EXISTS ix_crm_tareas_responsable ON crm_tareas (responsable_id, estado);
CREATE INDEX IF NOT EXISTS ix_crm_tareas_estado ON crm_tareas (estado, terminada_en);

CREATE TABLE IF NOT EXISTS crm_tarea_archivos (
  id             integer GENERATED BY DEFAULT AS IDENTITY,
  tarea_id       integer      NOT NULL,
  archivo_id     bigint       NOT NULL,
  tipo           varchar(10)  NOT NULL,
  nombre         varchar(255) NOT NULL,
  subido_por_id  integer      NULL,
  creado_en      timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT crm_tarea_archivos_pkey PRIMARY KEY (id),
  CONSTRAINT fk_crm_tarea_archivos_tarea FOREIGN KEY (tarea_id)
    REFERENCES crm_tareas (id) ON DELETE CASCADE,
  CONSTRAINT fk_crm_tarea_archivos_archivo FOREIGN KEY (archivo_id) REFERENCES crm_almacen_archivos (id),
  CONSTRAINT fk_crm_tarea_archivos_persona FOREIGN KEY (subido_por_id) REFERENCES crm_personas (id),
  CONSTRAINT ck_crm_tarea_archivos_tipo CHECK (tipo IN ('adjunto', 'entregable'))
);
CREATE INDEX IF NOT EXISTS ix_crm_tarea_archivos_tarea ON crm_tarea_archivos (tarea_id, tipo);
CREATE INDEX IF NOT EXISTS ix_crm_tarea_archivos_archivo ON crm_tarea_archivos (archivo_id);
CREATE INDEX IF NOT EXISTS ix_crm_tarea_archivos_persona ON crm_tarea_archivos (subido_por_id);

CREATE TABLE IF NOT EXISTS crm_tarea_eventos (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  tarea_id    integer       NOT NULL,
  tipo        varchar(20)   NOT NULL,
  actor       varchar(12)   NOT NULL,
  persona_id  integer       NULL,
  de_estado   varchar(12)   NULL,
  a_estado    varchar(12)   NULL,
  detalle     varchar(1000) NULL,
  ip          varchar(45)   COLLATE repositorio_ci NULL,
  creado_en   timestamptz(3) NOT NULL,
  CONSTRAINT crm_tarea_eventos_pkey PRIMARY KEY (id),
  CONSTRAINT fk_crm_tarea_eventos_tarea FOREIGN KEY (tarea_id)
    REFERENCES crm_tareas (id) ON DELETE CASCADE,
  CONSTRAINT fk_crm_tarea_eventos_persona FOREIGN KEY (persona_id) REFERENCES crm_personas (id),
  CONSTRAINT ck_crm_tarea_eventos_actor CHECK (actor IN ('lider', 'responsable'))
);
CREATE INDEX IF NOT EXISTS ix_crm_tarea_eventos_tarea ON crm_tarea_eventos (tarea_id, creado_en);
CREATE INDEX IF NOT EXISTS ix_crm_tarea_eventos_ip ON crm_tarea_eventos (ip, creado_en);
CREATE INDEX IF NOT EXISTS ix_crm_tarea_eventos_persona ON crm_tarea_eventos (persona_id);

CREATE TABLE IF NOT EXISTS crm_correos (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY,
  tarea_id           integer       NULL,
  tipo               varchar(20)   NOT NULL,
  para               varchar(254)  NOT NULL,
  responder_a        varchar(254)  NULL,
  asunto             varchar(255)  NOT NULL,
  cuerpo_texto       text          NOT NULL,
  cuerpo_html        text          NOT NULL,
  adjuntos           varchar(1000) NOT NULL DEFAULT '[]',
  estado             varchar(14)   NOT NULL DEFAULT 'pendiente',
  intentos           integer       NOT NULL DEFAULT 0,
  ultimo_error       varchar(1000) NULL,
  id_mensaje         varchar(255)  NULL,
  creado_en          timestamptz(3) NOT NULL,
  enviado_en         timestamptz(3) NULL,
  ultimo_intento_en  timestamptz(3) NULL,
  CONSTRAINT crm_correos_pkey PRIMARY KEY (id),
  CONSTRAINT fk_crm_correos_tarea FOREIGN KEY (tarea_id)
    REFERENCES crm_tareas (id) ON DELETE SET NULL,
  CONSTRAINT ck_crm_correos_estado CHECK (estado IN ('pendiente', 'enviado', 'error', 'sin_configurar')),
  CONSTRAINT ck_crm_correos_intentos CHECK (intentos >= 0)
);
CREATE INDEX IF NOT EXISTS ix_crm_correos_estado ON crm_correos (estado, creado_en);
CREATE INDEX IF NOT EXISTS ix_crm_correos_tarea ON crm_correos (tarea_id);

CREATE TABLE IF NOT EXISTS crm_acceso_usuarios (
  id               integer GENERATED BY DEFAULT AS IDENTITY,
  usuario          varchar(64)  COLLATE repositorio_ci NOT NULL,
  nombre           varchar(120) NULL,
  hash_contrasena  varchar(255) NOT NULL,
  activo           smallint     NOT NULL DEFAULT 1,
  ultimo_acceso    timestamptz(3) NULL,
  creado_en        timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en   timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT crm_acceso_usuarios_pkey PRIMARY KEY (id),
  CONSTRAINT uq_crm_acceso_usuarios_usuario UNIQUE (usuario),
  CONSTRAINT ck_crm_acceso_usuarios_activo CHECK (activo IN (0, 1))
);

CREATE TABLE IF NOT EXISTS crm_acceso_sesiones (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  token_hash  char(64) NOT NULL,
  csrf        char(43) NOT NULL,
  usuario_id  integer  NOT NULL,
  creada_en   timestamptz(3) NOT NULL,
  ultimo_uso  timestamptz(3) NOT NULL,
  expira_en   timestamptz(3) NOT NULL,
  ip          varchar(45)  NULL,
  agente      varchar(255) NULL,
  CONSTRAINT crm_acceso_sesiones_pkey PRIMARY KEY (id),
  CONSTRAINT uq_crm_acceso_sesiones_token UNIQUE (token_hash),
  CONSTRAINT fk_crm_acceso_sesiones_usuario FOREIGN KEY (usuario_id)
    REFERENCES crm_acceso_usuarios (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_crm_acceso_sesiones_usuario ON crm_acceso_sesiones (usuario_id);
CREATE INDEX IF NOT EXISTS ix_crm_acceso_sesiones_expira ON crm_acceso_sesiones (expira_en);

CREATE TABLE IF NOT EXISTS crm_acceso_intentos (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  usuario    varchar(64) COLLATE repositorio_ci NOT NULL,
  ip         varchar(45) COLLATE repositorio_ci NOT NULL,
  exito      smallint    NOT NULL,
  creado_en  timestamptz(3) NOT NULL,
  CONSTRAINT crm_acceso_intentos_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_crm_acceso_intentos_usuario ON crm_acceso_intentos (usuario, creado_en);
CREATE INDEX IF NOT EXISTS ix_crm_acceso_intentos_ip ON crm_acceso_intentos (ip, creado_en);
CREATE INDEX IF NOT EXISTS ix_crm_acceso_intentos_fecha ON crm_acceso_intentos (creado_en);

-- actualizado_en se toca en cada UPDATE (el ON UPDATE de MySQL), con la función del esquema.
DROP TRIGGER IF EXISTS tr_crm_personas_actualizado ON crm_personas;
CREATE TRIGGER tr_crm_personas_actualizado BEFORE UPDATE ON crm_personas
  FOR EACH ROW EXECUTE FUNCTION repositorio_tocar_actualizado();
DROP TRIGGER IF EXISTS tr_crm_tareas_actualizado ON crm_tareas;
CREATE TRIGGER tr_crm_tareas_actualizado BEFORE UPDATE ON crm_tareas
  FOR EACH ROW EXECUTE FUNCTION repositorio_tocar_actualizado();
DROP TRIGGER IF EXISTS tr_crm_acceso_usuarios_actualizado ON crm_acceso_usuarios;
CREATE TRIGGER tr_crm_acceso_usuarios_actualizado BEFORE UPDATE ON crm_acceso_usuarios
  FOR EACH ROW EXECUTE FUNCTION repositorio_tocar_actualizado();

-- Cerrado a la API pública de Supabase, como el resto del esquema.
ALTER TABLE crm_almacen_archivos ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_almacen_archivo_trozos ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_personas ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_tareas ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_tarea_archivos ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_tarea_eventos ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_correos ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_acceso_usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_acceso_sesiones ENABLE ROW LEVEL SECURITY;
ALTER TABLE crm_acceso_intentos ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
     AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON crm_almacen_archivos, crm_almacen_archivo_trozos, crm_personas, crm_tareas,
      crm_tarea_archivos, crm_tarea_eventos, crm_correos, crm_acceso_usuarios, crm_acceso_sesiones,
      crm_acceso_intentos FROM anon, authenticated;
  END IF;
END
$$;
