-- =============================================================================
-- Migración 3 (Postgres): Plan de Acción Institucional (rama /pai). La misma
-- de db/repositorio/migraciones/003-pai.sql (MySQL), traducida: IDENTITY,
-- timestamptz(3), smallint + CHECK, numeric(24,10), disparador
-- repositorio_tocar_actualizado() para actualizado_en, usuarios sin
-- distinguir mayúsculas (repositorio_ci), RLS activo sin políticas y sin
-- permisos para anon/authenticated (Supabase).
-- Se aplica dentro de la transacción de `npm run repositorio:migrar` (o
-- completa en el editor SQL de Supabase). No inserta en sistema_esquema_version.
-- =============================================================================

CREATE TABLE IF NOT EXISTS pai_usuarios (
  id                       integer GENERATED BY DEFAULT AS IDENTITY,
  usuario                  varchar(64)  COLLATE repositorio_ci NOT NULL,
  nombre                   varchar(120) NOT NULL,
  correo                   varchar(254) NULL,
  cargo                    varchar(160) NULL,
  rol                      varchar(15)  NOT NULL,
  hash_contrasena          varchar(255) NOT NULL,
  debe_cambiar_contrasena  smallint     NOT NULL DEFAULT 0,
  activo                   smallint     NOT NULL DEFAULT 1,
  ultimo_acceso            timestamptz(3) NULL,
  creado_en                timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en           timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT pai_usuarios_pkey PRIMARY KEY (id),
  CONSTRAINT uq_pai_usuarios_usuario UNIQUE (usuario),
  CONSTRAINT ck_pai_usuarios_rol CHECK (rol IN ('responsable', 'administrador')),
  CONSTRAINT ck_pai_usuarios_banderas CHECK (debe_cambiar_contrasena IN (0, 1) AND activo IN (0, 1))
);

CREATE TABLE IF NOT EXISTS pai_sesiones (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  token_hash  char(64) NOT NULL,
  csrf        char(43) NOT NULL,
  usuario_id  integer  NOT NULL,
  creada_en   timestamptz(3) NOT NULL,
  ultimo_uso  timestamptz(3) NOT NULL,
  expira_en   timestamptz(3) NOT NULL,
  ip          varchar(45)  NULL,
  agente      varchar(255) NULL,
  CONSTRAINT pai_sesiones_pkey PRIMARY KEY (id),
  CONSTRAINT uq_pai_sesiones_token UNIQUE (token_hash),
  CONSTRAINT fk_pai_sesiones_usuario FOREIGN KEY (usuario_id)
    REFERENCES pai_usuarios (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_pai_sesiones_usuario ON pai_sesiones (usuario_id);
CREATE INDEX IF NOT EXISTS ix_pai_sesiones_expira ON pai_sesiones (expira_en);

CREATE TABLE IF NOT EXISTS pai_intentos_acceso (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  usuario    varchar(64) COLLATE repositorio_ci NOT NULL,
  ip         varchar(45) COLLATE repositorio_ci NOT NULL,
  exito      smallint    NOT NULL,
  creado_en  timestamptz(3) NOT NULL,
  CONSTRAINT pai_intentos_acceso_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_pai_intentos_usuario ON pai_intentos_acceso (usuario, creado_en);
CREATE INDEX IF NOT EXISTS ix_pai_intentos_ip ON pai_intentos_acceso (ip, creado_en);
CREATE INDEX IF NOT EXISTS ix_pai_intentos_fecha ON pai_intentos_acceso (creado_en);

CREATE TABLE IF NOT EXISTS pai_vigencias (
  id                integer GENERATED BY DEFAULT AS IDENTITY,
  anio              smallint NOT NULL,
  bimestre_abierto  smallint NULL,
  abierto_hasta     timestamptz(3) NULL,
  extras            text     NULL,
  actualizado_en    timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_por   integer  NULL,
  CONSTRAINT pai_vigencias_pkey PRIMARY KEY (id),
  CONSTRAINT uq_pai_vigencias_anio UNIQUE (anio),
  CONSTRAINT fk_pai_vigencias_usuario FOREIGN KEY (actualizado_por)
    REFERENCES pai_usuarios (id) ON DELETE SET NULL,
  CONSTRAINT ck_pai_vigencias_anio CHECK (anio BETWEEN 2000 AND 2100),
  CONSTRAINT ck_pai_vigencias_bimestre CHECK (bimestre_abierto IS NULL OR bimestre_abierto BETWEEN 1 AND 6),
  CONSTRAINT ck_pai_vigencias_hasta CHECK (abierto_hasta IS NULL OR bimestre_abierto IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_pai_vigencias_actualizado_por ON pai_vigencias (actualizado_por);

CREATE TABLE IF NOT EXISTS pai_dependencias (
  id           integer GENERATED BY DEFAULT AS IDENTITY,
  vigencia_id  integer      NOT NULL,
  sigla        varchar(20)  NOT NULL,
  nombre       varchar(200) NOT NULL,
  orden        smallint     NOT NULL DEFAULT 0,
  CONSTRAINT pai_dependencias_pkey PRIMARY KEY (id),
  CONSTRAINT uq_pai_dependencias_sigla UNIQUE (vigencia_id, sigla),
  CONSTRAINT fk_pai_dependencias_vigencia FOREIGN KEY (vigencia_id) REFERENCES pai_vigencias (id)
);

CREATE TABLE IF NOT EXISTS pai_procesos (
  id                          integer GENERATED BY DEFAULT AS IDENTITY,
  vigencia_id                 integer      NOT NULL,
  dependencia_id              integer      NOT NULL,
  clave                       varchar(60)  NOT NULL,
