CREATE INDEX IF NOT EXISTS ix_pai_reportes_actualizado_por ON pai_reportes (actualizado_por);

-- Almacén de archivos del PAI, aparte del del repositorio (ver la migración
-- de MySQL). La migración 004 crea estas dos tablas igual en las bases que ya
-- tenían esta migración sin ellas.
CREATE TABLE IF NOT EXISTS pai_almacen_archivos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  sha256        char(64)     NOT NULL,
  mime          varchar(127) NOT NULL,
  bytes         bigint       NOT NULL,
  trozos        integer      NOT NULL,
  tamano_trozo  integer      NOT NULL,
  ancho         integer      NULL,
  alto          integer      NULL,
  creado_en     timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT pai_almacen_archivos_pkey PRIMARY KEY (id),
  CONSTRAINT uq_pai_almacen_archivos_sha256 UNIQUE (sha256),
  CONSTRAINT ck_pai_almacen_archivos_trozo CHECK (tamano_trozo > 0),
  CONSTRAINT ck_pai_almacen_archivos_bytes CHECK (bytes >= 0 AND trozos >= 0)
);

CREATE TABLE IF NOT EXISTS pai_almacen_archivo_trozos (
  archivo_id  bigint  NOT NULL,
  n           integer NOT NULL,
  datos       bytea   NOT NULL,
  CONSTRAINT pai_almacen_archivo_trozos_pkey PRIMARY KEY (archivo_id, n),
  CONSTRAINT fk_pai_almacen_archivo_trozos_archivo FOREIGN KEY (archivo_id)
    REFERENCES pai_almacen_archivos (id) ON DELETE CASCADE
);

