CREATE TABLE IF NOT EXISTS sivu_acceso_usuarios (
  id               integer GENERATED BY DEFAULT AS IDENTITY,
  usuario          varchar(64)  COLLATE repositorio_ci NOT NULL,
  nombre           varchar(120) NULL,
  hash_contrasena  varchar(255) NOT NULL,
  activo           smallint     NOT NULL DEFAULT 1,
  ultimo_acceso    timestamptz(3) NULL,
  creado_en        timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en   timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT sivu_acceso_usuarios_pkey PRIMARY KEY (id),
  CONSTRAINT uq_sivu_acceso_usuarios_usuario UNIQUE (usuario),
  CONSTRAINT ck_sivu_acceso_usuarios_activo CHECK (activo IN (0, 1))
);

CREATE TABLE IF NOT EXISTS sivu_acceso_sesiones (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  token_hash  char(64) NOT NULL,
  csrf        char(43) NOT NULL,
  usuario_id  integer  NOT NULL,
  creada_en   timestamptz(3) NOT NULL,
  ultimo_uso  timestamptz(3) NOT NULL,
  expira_en   timestamptz(3) NOT NULL,
  ip          varchar(45)  NULL,
  agente      varchar(255) NULL,
  CONSTRAINT sivu_acceso_sesiones_pkey PRIMARY KEY (id),
  CONSTRAINT uq_sivu_acceso_sesiones_token UNIQUE (token_hash),
  CONSTRAINT fk_sivu_acceso_sesiones_usuario FOREIGN KEY (usuario_id)
    REFERENCES sivu_acceso_usuarios (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_sivu_acceso_sesiones_usuario ON sivu_acceso_sesiones (usuario_id);
CREATE INDEX IF NOT EXISTS ix_sivu_acceso_sesiones_expira ON sivu_acceso_sesiones (expira_en);

CREATE TABLE IF NOT EXISTS sivu_acceso_intentos (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  usuario    varchar(64) COLLATE repositorio_ci NOT NULL,
  ip         varchar(45) COLLATE repositorio_ci NOT NULL,
  exito      smallint    NOT NULL,
  creado_en  timestamptz(3) NOT NULL,
  CONSTRAINT sivu_acceso_intentos_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_sivu_acceso_intentos_usuario ON sivu_acceso_intentos (usuario, creado_en);
CREATE INDEX IF NOT EXISTS ix_sivu_acceso_intentos_ip ON sivu_acceso_intentos (ip, creado_en);
CREATE INDEX IF NOT EXISTS ix_sivu_acceso_intentos_fecha ON sivu_acceso_intentos (creado_en);

-- actualizado_en se toca en cada UPDATE (el ON UPDATE de MySQL), con la función del esquema.
DROP TRIGGER IF EXISTS tr_sivu_acceso_usuarios_actualizado ON sivu_acceso_usuarios;
CREATE TRIGGER tr_sivu_acceso_usuarios_actualizado BEFORE UPDATE ON sivu_acceso_usuarios
  FOR EACH ROW EXECUTE FUNCTION repositorio_tocar_actualizado();

-- Cerrado a la API pública de Supabase, como el resto del esquema.
ALTER TABLE sivu_acceso_usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE sivu_acceso_sesiones ENABLE ROW LEVEL SECURITY;
ALTER TABLE sivu_acceso_intentos ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
     AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON sivu_acceso_usuarios, sivu_acceso_sesiones, sivu_acceso_intentos FROM anon, authenticated;
  END IF;
END
$$;
