BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon')
     AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON sistema_esquema_version, repositorio_estado, repositorio_categorias, repositorio_almacen_archivos, repositorio_almacen_archivo_trozos,
      repositorio_documentos, repositorio_palabras_clave, repositorio_documento_palabras_clave, repositorio_administradores, repositorio_sesiones,
      repositorio_intentos_acceso, repositorio_cambios FROM anon, authenticated;
    REVOKE EXECUTE ON FUNCTION repositorio_tocar_actualizado() FROM anon, authenticated, PUBLIC;
  END IF;
END
$$;

