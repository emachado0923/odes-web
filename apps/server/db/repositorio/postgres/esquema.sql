-- =============================================================================
-- Repositorio de Productos del Observatorio de Sapiencia (rama /repositorio)
-- Esquema Postgres, versión 1: el mismo de db/repositorio/esquema.sql (MySQL).
--
-- * Para Supabase u otro Postgres 15 o superior con ICU.
-- * Idempotente: se puede ejecutar todas las veces que haga falta
--   (IF NOT EXISTS, ON CONFLICT DO NOTHING). No borra ni cambia datos.
-- * Lo aplica `npm run repositorio:migrar` (en una transacción) o el editor
--   SQL de Supabase, completo.
-- * Los mismos nombres de tablas, columnas, índices y restricciones que en
--   MySQL: el servidor usa las mismas consultas en los dos motores.
-- * Equivalencias: TINYINT(1) -> smallint 0/1, DATETIME(3) en UTC ->
--   timestamptz(3), ENUM -> texto con CHECK, AUTO_INCREMENT -> IDENTITY,
--   MEDIUMBLOB -> bytea, ON UPDATE CURRENT_TIMESTAMP -> disparador. Las
--   intercalaciones _ai_ci de MySQL (sin distinguir tildes ni mayúsculas)
--   son las intercalaciones ICU no deterministas repositorio_ci_ai y
--   repositorio_ci.
-- * Seguridad en Supabase: RLS activo y sin políticas en todas las tablas, y
--   sin permisos para los roles anon y authenticated. Así la API pública de
--   Supabase (con la clave publicable) no ve nada de esto; solo el servidor,
--   que se conecta con el usuario dueño de las tablas.
-- =============================================================================

-- Sin distinguir tildes ni mayúsculas ("Boletín" = "boletin"), como utf8mb4_0900_ai_ci.
CREATE COLLATION IF NOT EXISTS repositorio_ci_ai (provider = icu, locale = 'und-u-ks-level1', deterministic = false);
-- Sin distinguir mayúsculas, sí tildes, como ascii_general_ci (usuarios, IP).
CREATE COLLATION IF NOT EXISTS repositorio_ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

-- Guarda de la versión 4: sobre una base que todavía tiene los nombres de tabla
-- anteriores, este archivo se detiene aquí sin crear nada (si no, crearía las
-- tablas nuevas vacías junto a las viejas). `npm run repositorio:migrar`
-- renombra antes de aplicarlo, así que nunca llega a esta guarda.
DO $$
BEGIN
  IF to_regclass('esquema_version') IS NOT NULL THEN
    RAISE EXCEPTION 'La base tiene los nombres de tabla anteriores a la versión 4 (esquema_version, documentos, archivos...). Páselos primero a los nuevos con npm run repositorio:migrar o a mano: ver "Paso a la versión 4" en apps/server/db/repositorio/LEEME.md.';
  END IF;
END
$$;

-- Versión del esquema aplicada (la consulta el servidor al conectarse).
CREATE TABLE IF NOT EXISTS sistema_esquema_version (
  version      integer      NOT NULL,
  descripcion  varchar(200) NOT NULL,
  aplicado_en  timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT esquema_version_pkey PRIMARY KEY (version)
);

-- Una sola fila: contador de cambios del contenido público (ver la versión MySQL).
CREATE TABLE IF NOT EXISTS repositorio_estado (
  id              smallint NOT NULL,
  version         bigint   NOT NULL DEFAULT 0,
  actualizado_en  timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT estado_repositorio_pkey PRIMARY KEY (id),
  CONSTRAINT ck_estado_repositorio_unico CHECK (id = 1)
);

INSERT INTO repositorio_estado (id, version) VALUES (1, 0) ON CONFLICT (id) DO NOTHING;

-- Categorías. El nombre es único sin distinguir tildes ni mayúsculas.
CREATE TABLE IF NOT EXISTS repositorio_categorias (
  id              integer GENERATED BY DEFAULT AS IDENTITY,
  nombre          varchar(100) COLLATE repositorio_ci_ai NOT NULL,
  orden           integer NOT NULL DEFAULT 0,
  creado_en       timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en  timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT categorias_pkey PRIMARY KEY (id),
  CONSTRAINT uq_categorias_nombre UNIQUE (nombre),
  CONSTRAINT ck_categorias_orden CHECK (orden >= 0)
);
CREATE INDEX IF NOT EXISTS ix_categorias_orden ON repositorio_categorias (orden);

-- Almacén de archivos del repositorio: documento, portada o miniatura (las
-- evidencias del PAI tienen su propio almacén, pai_almacen_archivos). Con
-- Supabase Storage el contenido va en el bucket público
-- (archivos/<id>-<sha256>.<extensión>) y repositorio_almacen_archivo_trozos
-- queda vacía; sin Storage, va en repositorio_almacen_archivo_trozos como en
-- MySQL.
CREATE TABLE IF NOT EXISTS repositorio_almacen_archivos (
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  sha256        char(64)     NOT NULL,
  mime          varchar(127) NOT NULL,
  bytes         bigint       NOT NULL,
  trozos        integer      NOT NULL,
  tamano_trozo  integer      NOT NULL,
  ancho         integer      NULL,
  alto          integer      NULL,
  creado_en     timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT archivos_pkey PRIMARY KEY (id),
  CONSTRAINT uq_archivos_sha256 UNIQUE (sha256),
  CONSTRAINT ck_archivos_trozo CHECK (tamano_trozo > 0),
  CONSTRAINT ck_archivos_bytes CHECK (bytes >= 0 AND trozos >= 0)
);

CREATE TABLE IF NOT EXISTS repositorio_almacen_archivo_trozos (
  archivo_id  bigint  NOT NULL,
  n           integer NOT NULL,
  datos       bytea   NOT NULL,
  CONSTRAINT archivo_trozos_pkey PRIMARY KEY (archivo_id, n),
  CONSTRAINT fk_archivo_trozos_archivo FOREIGN KEY (archivo_id)
    REFERENCES repositorio_almacen_archivos (id) ON DELETE CASCADE
);

-- Productos del repositorio.
CREATE TABLE IF NOT EXISTS repositorio_documentos (
  id                      varchar(120)  NOT NULL,
  orden                   integer       NOT NULL,
  titulo                  varchar(300)  NOT NULL,
  subtitulo               varchar(400)  NULL,
  descripcion             varchar(700)  NULL,
  categoria_id            integer       NOT NULL,
  numero                  varchar(20)   NULL,
  anio                    smallint      NULL,
  mes                     smallint      NULL,
  idioma                  varchar(2)    NOT NULL,
  tipo                    varchar(10)   NOT NULL,
  url_ver_externa         varchar(2048) NULL,
  url_entrada_blog        varchar(2048) NULL,
  nota                    varchar(300)  NULL,
  permite_descarga        smallint      NOT NULL DEFAULT 0,
  equivalente_en_espanol  varchar(400)  NULL,
  notas_internas          text          NULL,
  archivo_id              bigint        NULL,
  portada_id              bigint        NULL,
  miniatura_id            bigint        NULL,
  publicado               smallint      NOT NULL DEFAULT 0,
  -- Referencia histórica de la carga inicial. Solo lectura.
  url_original            varchar(2048) NULL,
  url_descarga_original   varchar(2048) NULL,
  pagina_original         varchar(200)  NULL,
  subido_original         char(7)       NULL,
  creado_en               timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en          timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_por         varchar(64)   NULL,
  CONSTRAINT documentos_pkey PRIMARY KEY (id),
  CONSTRAINT fk_documentos_categoria FOREIGN KEY (categoria_id) REFERENCES repositorio_categorias (id),
  CONSTRAINT fk_documentos_archivo FOREIGN KEY (archivo_id) REFERENCES repositorio_almacen_archivos (id),
  CONSTRAINT fk_documentos_portada FOREIGN KEY (portada_id) REFERENCES repositorio_almacen_archivos (id),
  CONSTRAINT fk_documentos_miniatura FOREIGN KEY (miniatura_id) REFERENCES repositorio_almacen_archivos (id),
  CONSTRAINT ck_documentos_idioma CHECK (idioma IN ('es', 'en')),
  CONSTRAINT ck_documentos_tipo CHECK (tipo IN ('documento', 'tablero', 'entrada')),
  CONSTRAINT ck_documentos_banderas CHECK (permite_descarga IN (0, 1) AND publicado IN (0, 1)),
  CONSTRAINT ck_documentos_anio CHECK (anio IS NULL OR anio BETWEEN 1900 AND 2200),
  CONSTRAINT ck_documentos_mes CHECK (mes IS NULL OR (mes BETWEEN 1 AND 12 AND anio IS NOT NULL)),
  CONSTRAINT ck_documentos_orden CHECK (orden >= 1)
);
CREATE INDEX IF NOT EXISTS ix_documentos_publicado_orden ON repositorio_documentos (publicado, orden);
CREATE INDEX IF NOT EXISTS ix_documentos_orden ON repositorio_documentos (orden);
CREATE INDEX IF NOT EXISTS ix_documentos_categoria ON repositorio_documentos (categoria_id);
CREATE INDEX IF NOT EXISTS ix_documentos_archivo ON repositorio_documentos (archivo_id);
CREATE INDEX IF NOT EXISTS ix_documentos_portada ON repositorio_documentos (portada_id);
CREATE INDEX IF NOT EXISTS ix_documentos_miniatura ON repositorio_documentos (miniatura_id);

-- Palabras clave. `clave` es el texto normalizado por la aplicación
-- (minúsculas, sin tildes): se compara tal cual.
CREATE TABLE IF NOT EXISTS repositorio_palabras_clave (
  id         integer GENERATED BY DEFAULT AS IDENTITY,
  texto      varchar(80) COLLATE repositorio_ci_ai NOT NULL,
  clave      varchar(80) NOT NULL,
  creado_en  timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT palabras_clave_pkey PRIMARY KEY (id),
  CONSTRAINT uq_palabras_clave_clave UNIQUE (clave)
);

CREATE TABLE IF NOT EXISTS repositorio_documento_palabras_clave (
  documento_id  varchar(120) NOT NULL,
  palabra_id    integer      NOT NULL,
  posicion      smallint     NOT NULL,
  CONSTRAINT documento_palabras_clave_pkey PRIMARY KEY (documento_id, palabra_id),
  CONSTRAINT fk_documento_palabras_documento FOREIGN KEY (documento_id)
    REFERENCES repositorio_documentos (id) ON DELETE CASCADE,
  CONSTRAINT fk_documento_palabras_palabra FOREIGN KEY (palabra_id)
    REFERENCES repositorio_palabras_clave (id)
);
CREATE INDEX IF NOT EXISTS ix_documento_palabras_palabra ON repositorio_documento_palabras_clave (palabra_id);

-- Usuarios de la administración (scrypt; npm run repositorio:crear-admin).
CREATE TABLE IF NOT EXISTS repositorio_administradores (
  id               integer GENERATED BY DEFAULT AS IDENTITY,
  usuario          varchar(64)  COLLATE repositorio_ci NOT NULL,
  nombre           varchar(120) NULL,
  hash_contrasena  varchar(255) NOT NULL,
  activo           smallint     NOT NULL DEFAULT 1,
  ultimo_acceso    timestamptz(3) NULL,
  creado_en        timestamptz(3) NOT NULL DEFAULT now(),
  actualizado_en   timestamptz(3) NOT NULL DEFAULT now(),
  CONSTRAINT administradores_pkey PRIMARY KEY (id),
  CONSTRAINT uq_administradores_usuario UNIQUE (usuario),
  CONSTRAINT ck_administradores_activo CHECK (activo IN (0, 1))
);

-- Sesiones de la administración (solo el sha256 del token de la cookie).
CREATE TABLE IF NOT EXISTS repositorio_sesiones (
  id          bigint GENERATED BY DEFAULT AS IDENTITY,
  token_hash  char(64) NOT NULL,
  csrf        char(43) NOT NULL,
  usuario_id  integer  NOT NULL,
  creada_en   timestamptz(3) NOT NULL,
  ultimo_uso  timestamptz(3) NOT NULL,
  expira_en   timestamptz(3) NOT NULL,
  ip          varchar(45)  NULL,
  agente      varchar(255) NULL,
  CONSTRAINT sesiones_pkey PRIMARY KEY (id),
  CONSTRAINT uq_sesiones_token UNIQUE (token_hash),
  CONSTRAINT fk_sesiones_usuario FOREIGN KEY (usuario_id)
    REFERENCES repositorio_administradores (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_sesiones_usuario ON repositorio_sesiones (usuario_id);
CREATE INDEX IF NOT EXISTS ix_sesiones_expira ON repositorio_sesiones (expira_en);

-- Intentos de inicio de sesión (límite y bloqueo temporal por usuario y por IP).
CREATE TABLE IF NOT EXISTS repositorio_intentos_acceso (
  id         bigint GENERATED BY DEFAULT AS IDENTITY,
  usuario    varchar(64) COLLATE repositorio_ci NOT NULL,
  ip         varchar(45) COLLATE repositorio_ci NOT NULL,
  exito      smallint    NOT NULL,
  creado_en  timestamptz(3) NOT NULL,
  CONSTRAINT intentos_acceso_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_intentos_usuario ON repositorio_intentos_acceso (usuario, creado_en);
CREATE INDEX IF NOT EXISTS ix_intentos_ip ON repositorio_intentos_acceso (ip, creado_en);
CREATE INDEX IF NOT EXISTS ix_intentos_fecha ON repositorio_intentos_acceso (creado_en);

-- Registro de cambios (auditoría), sin llave foránea a documentos.
CREATE TABLE IF NOT EXISTS repositorio_cambios (
  id            bigint GENERATED BY DEFAULT AS IDENTITY,
  fecha         timestamptz(3) NOT NULL,
  usuario       varchar(64)   NULL,
  accion        varchar(30)   NOT NULL,
  documento_id  varchar(120)  NULL,
  detalle       varchar(1000) NULL,
  CONSTRAINT cambios_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_cambios_fecha ON repositorio_cambios (fecha);
CREATE INDEX IF NOT EXISTS ix_cambios_documento ON repositorio_cambios (documento_id, id);

-- ON UPDATE CURRENT_TIMESTAMP(3) de MySQL.
CREATE OR REPLACE FUNCTION repositorio_tocar_actualizado() RETURNS trigger
  LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  NEW.actualizado_en := now();
  RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS tr_categorias_actualizado ON repositorio_categorias;
CREATE TRIGGER tr_categorias_actualizado BEFORE UPDATE ON repositorio_categorias
  FOR EACH ROW EXECUTE FUNCTION repositorio_tocar_actualizado();

DROP TRIGGER IF EXISTS tr_administradores_actualizado ON repositorio_administradores;
CREATE TRIGGER tr_administradores_actualizado BEFORE UPDATE ON repositorio_administradores
  FOR EACH ROW EXECUTE FUNCTION repositorio_tocar_actualizado();

